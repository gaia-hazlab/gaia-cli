"""``gaia catalog`` – a STAC catalog of the stores under a prefix.

Every ``gaia stage``/``gaia align`` run writes a STAC Item next to its store
(``<name>.zarr`` → ``<name>.json``). ``gaia catalog rebuild`` lists those
Items and writes a ``catalog.json`` linking them. Every href is relative, so
the catalog works wherever the prefix is served (e.g. in stac-browser), and
rebuilding from a listing drops Items whose store has since been deleted.
See dev/stac-catalog.md.
"""

from __future__ import annotations

import json
import logging
import posixpath
from concurrent.futures import ThreadPoolExecutor
from functools import partial
from typing import Annotated, TypeGuard

import obstore
from cyclopts import Parameter

from . import io

log = logging.getLogger(__name__)

CATALOG_KEY = "catalog.json"
JSON = "application/json"
GEOJSON = "application/geo+json"


def find_json(store) -> list[str]:
    """Keys of ``.json`` files under *store*, without descending into Zarr stores."""
    keys: list[str] = []
    prefixes: list[str | None] = [None]
    while prefixes:
        listing = obstore.list_with_delimiter(store, prefix=prefixes.pop())
        prefixes += [p for p in listing["common_prefixes"] if not p.endswith(".zarr")]
        keys += [
            o["path"]
            for o in listing["objects"]
            if o["path"].endswith(".json")
            and posixpath.basename(o["path"]) != CATALOG_KEY
        ]
    return sorted(keys)


def _read_json(store, key: str) -> dict | None:
    try:
        doc = json.loads(bytes(obstore.get(store, key).bytes()))
    except (FileNotFoundError, ValueError):
        return None
    return doc if isinstance(doc, dict) else None


def is_gaia_item(doc: dict | None) -> TypeGuard[dict]:
    """Whether *doc* is a STAC Item written by gaia-cli for a store."""
    return (
        doc is not None
        and doc.get("type") == "Feature"
        and "gaia:cli-version" in doc.get("properties", {})
        and "data" in doc.get("assets", {})
    )


def store_exists(store, key: str, item: dict) -> bool:
    """Whether the Zarr store that the Item at *key* describes still exists."""
    href = item["assets"]["data"]["href"]
    zarr_key = posixpath.normpath(posixpath.join(posixpath.dirname(key), href))
    try:
        obstore.head(store, f"{zarr_key}/zarr.json")
    except FileNotFoundError:
        return False
    return True


def build_catalog(items: dict[str, dict], prefix: str) -> dict:
    """A STAC Catalog linking *items* (``{key: item}``, keys relative to it)."""
    links = [{"rel": "root", "href": f"./{CATALOG_KEY}", "type": JSON}]
    for key, item in sorted(items.items()):
        title = item["properties"].get("title") or item["id"]
        links.append(
            {"rel": "item", "href": f"./{key}", "type": GEOJSON, "title": title}
        )
    return {
        "type": "Catalog",
        "stac_version": "1.1.0",
        "id": "gaia-stores",
        "title": "gaia staged stores",
        "description": (
            f"Zarr stores written by gaia-cli under {prefix}, one STAC Item "
            "each. Regenerated by `gaia catalog rebuild`; stores and Items "
            "here may be temporary."
        ),
        "links": links,
    }


def rebuild(prefix: Annotated[str, Parameter(name=["--prefix", "-p"])]):
    """Write a STAC catalog of the gaia stores under PREFIX.

    Finds the Items that ``gaia stage``/``gaia align`` write next to their
    stores, skips any whose store was deleted, and writes
    ``PREFIX/catalog.json``. Requires AWS_PROFILE for an ``s3://`` PREFIX.

    Parameters
    ----------
    prefix : str
        Local directory or ``s3://`` URL holding staged stores.

    Examples
    --------
        $ gaia catalog rebuild -p s3://gaia/scratch
    """
    io.check_s3_env(prefix)
    store = io.object_store(prefix)
    keys = find_json(store)
    with ThreadPoolExecutor(max_workers=16) as pool:
        docs = dict(zip(keys, pool.map(partial(_read_json, store), keys), strict=True))
    items = {k: doc for k, doc in docs.items() if is_gaia_item(doc)}
    live = {k: it for k, it in items.items() if store_exists(store, k, it)}
    for key in items.keys() - live.keys():
        log.info("skipping %s: its store no longer exists", key)

    io.write_json(f"{prefix.rstrip('/')}/{CATALOG_KEY}", build_catalog(live, prefix))
    log.info("Wrote %s/%s with %d item(s)", prefix.rstrip("/"), CATALOG_KEY, len(live))
